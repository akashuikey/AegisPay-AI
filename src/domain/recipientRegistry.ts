/**
 * Resolve any entered UPI ID against the persistent 20-account registry.
 * If unknown, creates a deterministic unestablished profile without assuming fraud.
 */
export function resolveRecipient(upiId: string): FictionalRecipient {
  const normalized = upiId.trim().toLowerCase();
  const match = RECIPIENT_REGISTRY.find(
    (r) => r.upi_id.toLowerCase() === normalized || normalized.includes(r.upi_id.toLowerCase())
  );
  if (match) return match;

  // Unknown recipient profile (controlled unknown case)
  return {
    id: `rec_unknown_${Math.abs(hashString(normalized))}`,
    upi_id: upiId,
    display_name: formatFallbackName(upiId),
    bank_name: 'Unknown Interbank Rail',
    region: 'Unverified Origin',
    account_age_days: 15,
    account_status: 'ACTIVE',
    category: 'PERSONAL',
    is_trusted_beneficiary: false,
    typical_min_amount: 100,
    typical_max_amount: 50000,
    avg_monthly_transfer_count: 0,
    fan_in_count_24h: 1,
    fan_out_count_24h: 1,
    is_flagged_mule: false,
    payee_name_mismatch: false,
    routing_mismatch: false,
    risk_tier: 'MEDIUM',
    default_risk_score: 35,
    notes: 'Unregistered beneficiary with no prior customer transaction history.',
  };
}

function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return hash;
}

function formatFallbackName(upi: string): string {
  const handle = upi.split('@')[0] || upi;
  return handle
    .split(/[._-]/)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');
}
