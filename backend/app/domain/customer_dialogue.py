"""Domain models, prompts, and schemas for dynamic Gemini-powered customer dialogue.

Supports both simulated voice calls and interactive customer chat.
Ensures strict prompt injection defenses, non-accusatory customer communication,
and evidence-linked forensic observations. The AI investigates and inquires;
it never mutates transaction state directly.
"""

from __future__ import annotations

import json
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from app.domain.investigation import RiskSentiment


class DialogueChannel(StrEnum):
    """Channel used for the simulated customer dialogue."""

    VOICE_SIMULATED = "VOICE_SIMULATED"
    CHAT_SIMULATED = "CHAT_SIMULATED"


class CallSessionStatus(StrEnum):
    """Lifecycle states for a simulated call session."""

    INITIATED = "INITIATED"
    RINGING = "RINGING"
    CONNECTED = "CONNECTED"
    COMPLETED = "COMPLETED"
    DECLINED = "DECLINED"
    TIMED_OUT = "TIMED_OUT"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class CallSessionDirection(StrEnum):
    """Direction of the simulated call session."""

    OUTBOUND_SIMULATED = "OUTBOUND_SIMULATED"
    INBOUND_SIMULATED = "INBOUND_SIMULATED"


TERMINAL_CALL_STATUSES = frozenset(
    {
        CallSessionStatus.COMPLETED,
        CallSessionStatus.DECLINED,
        CallSessionStatus.TIMED_OUT,
        CallSessionStatus.FAILED,
        CallSessionStatus.CANCELLED,
    }
)


class SuggestedAction(StrEnum):
    """Advisory action suggested by the dialogue model to the deterministic workflow."""

    CONTINUE_INQUIRY = "CONTINUE_INQUIRY"
    RECOMMEND_REEVALUATION = "RECOMMEND_REEVALUATION"
    RECOMMEND_HOLD = "RECOMMEND_HOLD"


# ---------------------------------------------------------------------------
# Structured Output Schema for Gemini Model Calling
# ---------------------------------------------------------------------------


class CustomerDialogueTurnResult(BaseModel):
    """Structured forensic and conversational output generated by Gemini for a customer turn."""

    model_config = ConfigDict(extra="ignore")

    assistant_message: str = Field(
        ...,
        description=(
            "Empathetic, clear, non-accusatory message or single question addressed to the customer"
        ),
    )
    internal_observations: list[str] = Field(
        default_factory=list,
        description="Objective forensic observations grounded in what the customer reported",
    )
    evidence_references: list[str] = Field(
        default_factory=list,
        description="Citations to input facts or statements (e.g. 'stmt_1', 'tx:recipient_name')",
    )
    uncertainty_notes: list[str] = Field(
        default_factory=list,
        description="Contradictions, missing info, or ambiguities requiring attention",
    )
    suggested_action: SuggestedAction = Field(
        default=SuggestedAction.CONTINUE_INQUIRY,
        description="Advisory recommendation for the deterministic fraud workflow",
    )
    is_terminal_turn: bool = Field(
        default=False,
        description="True if sufficient clarity has been obtained or inquiry should conclude",
    )
    risk_sentiment: RiskSentiment = Field(
        default=RiskSentiment.UNKNOWN,
        description="Forensic risk sentiment: BENIGN, SUSPICIOUS, COERCED, or UNKNOWN",
    )
    coercion_cues: list[str] = Field(
        default_factory=list,
        description="Specific coercion or pressure indicators identified in customer statements",
    )


